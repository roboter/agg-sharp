using MatterHackers.Agg.VertexSource;
using MatterHackers.Csg.Transform;
using MatterHackers.PolygonMesh;
using MatterHackers.PolygonMesh.Processors;
using MatterHackers.VectorMath;
using System;
using System.Collections.Generic;
using System.Linq;

namespace MatterHackers.Csg.Solids
{
    /// <summary>
    /// Represents a 2D cross-section at a specific Z height for a 3D loft operation.
    /// </summary>
    public struct LoftSection
    {
        /// <summary>
        /// The closed 2D primitive profile for this cross-section.
        /// </summary>
        public I2DPrimitive Shape { get; }

        /// <summary>
        /// The elevation (Z coordinate) where this cross-section is placed.
        /// </summary>
        public double Z { get; }

        public LoftSection(I2DPrimitive shape, double z)
        {
            Shape = shape ?? throw new ArgumentNullException(nameof(shape));
            Z = z;
        }

        public static implicit operator LoftSection((I2DPrimitive shape, double z) tuple)
            => new LoftSection(tuple.shape, tuple.z);

        public static implicit operator LoftSection((I2DPrimitive shape, int z) tuple)
            => new LoftSection(tuple.shape, tuple.z);

        public override string ToString() => $"LoftSection({Shape}, Z={Z})";
    }

    /// <summary>
    /// Represents a 3D solid generated by lofting (skinning) between two or more 2D cross-sections.
    /// For example: lofting a Rectangle at the bottom to a Circle at the top to create a square-to-round transition duct.
    /// </summary>
    public class Loft : CsgObjectWrapper
    {
        public IReadOnlyList<LoftSection> Sections { get; }
        public double TwistDegrees { get; }
        public int Resolution { get; }
        public bool Capped { get; }
        public bool Centered { get; }
        public Alignment Alignment { get; }

        /// <summary>
        /// Lofts between two 2D cross-sections across the specified height.
        /// </summary>
        public Loft(
            I2DPrimitive bottom,
            I2DPrimitive top,
            double height,
            double twistDegrees = 0,
            int resolution = 60,
            bool capped = true,
            bool centered = false,
            Alignment alignment = Alignment.z,
            string name = "")
            : this(
                CreateTwoSections(bottom, top, height),
                twistDegrees,
                resolution,
                capped,
                centered,
                alignment,
                name)
        {
        }

        /// <summary>
        /// Lofts between multiple 2D cross-sections placed at specific Z heights.
        /// </summary>
        public Loft(
            params LoftSection[] sections)
            : this((IEnumerable<LoftSection>)sections)
        {
        }

        /// <summary>
        /// Lofts between multiple 2D cross-sections with a total twist angle.
        /// </summary>
        public Loft(
            double twistDegrees,
            params LoftSection[] sections)
            : this(sections, twistDegrees: twistDegrees)
        {
        }

        /// <summary>
        /// Lofts between a sequence of 2D cross-sections.
        /// </summary>
        public Loft(
            IEnumerable<LoftSection> sections,
            double twistDegrees = 0,
            int resolution = 60,
            bool capped = true,
            bool centered = false,
            Alignment alignment = Alignment.z,
            string name = "")
            : base(name)
        {
            if (sections == null) throw new ArgumentNullException(nameof(sections));

            var sortedSections = sections.OrderBy(s => s.Z).ToList();
            if (sortedSections.Count < 2)
            {
                throw new ArgumentException("A loft requires at least 2 cross-sections.", nameof(sections));
            }

            for (int i = 1; i < sortedSections.Count; i++)
            {
                if (Math.Abs(sortedSections[i].Z - sortedSections[i - 1].Z) < 1e-9)
                {
                    throw new ArgumentException($"Consecutive loft sections cannot have identical Z height ({sortedSections[i].Z}).", nameof(sections));
                }
            }

            Sections = sortedSections.AsReadOnly();
            TwistDegrees = twistDegrees;
            Resolution = Math.Max(3, resolution);
            Capped = capped;
            Centered = centered;
            Alignment = alignment;

            Mesh mesh = BuildLoftMesh(sortedSections, TwistDegrees, Resolution, Capped, Centered);
            CsgObject csgMesh = new MeshContainer(mesh);
            root = Primitive2DHelpers.ApplyAlignment(csgMesh, alignment);
        }

        private static IEnumerable<LoftSection> CreateTwoSections(I2DPrimitive bottom, I2DPrimitive top, double height)
        {
            if (bottom == null) throw new ArgumentNullException(nameof(bottom));
            if (top == null) throw new ArgumentNullException(nameof(top));
            if (height <= 0)
            {
                throw new ArgumentOutOfRangeException(nameof(height), "Loft height must be greater than zero.");
            }
            return new[]
            {
                new LoftSection(bottom, 0),
                new LoftSection(top, height)
            };
        }

        private static Mesh BuildLoftMesh(
            List<LoftSection> sortedSections,
            double twistDegrees,
            int resolution,
            bool capped,
            bool centered)
        {
            int sectionCount = sortedSections.Count;
            double zMin = sortedSections[0].Z;
            double zMax = sortedSections[sectionCount - 1].Z;
            double totalHeight = zMax - zMin;

            // 1. Sample perimeter points for each section
            var sampledSections = new List<List<Vector2>>(sectionCount);

            for (int sIdx = 0; sIdx < sectionCount; sIdx++)
            {
                var section = sortedSections[sIdx];
                double progress = totalHeight > 1e-9 ? (section.Z - zMin) / totalHeight : 0.0;
                double twistAtSection = twistDegrees * progress;

                List<Vector2> loop = SampleLoop(section.Shape, resolution, twistAtSection);
                sampledSections.Add(loop);
            }

            var mesh = new Mesh();

            // 2. Generate side walls between consecutive sections
            for (int sIdx = 0; sIdx < sectionCount - 1; sIdx++)
            {
                var bottomLoop = sampledSections[sIdx];
                var topLoop = sampledSections[sIdx + 1];
                double zBottom = sortedSections[sIdx].Z;
                double zTop = sortedSections[sIdx + 1].Z;

                for (int i = 0; i < resolution; i++)
                {
                    int next = (i + 1) % resolution;

                    var b0 = new Vector3(bottomLoop[i], zBottom);
                    var b1 = new Vector3(bottomLoop[next], zBottom);
                    var t1 = new Vector3(topLoop[next], zTop);
                    var t0 = new Vector3(topLoop[i], zTop);

                    // Add two outward facing triangles for each quad strip
                    mesh.CreateFace(b0, b1, t1);
                    mesh.CreateFace(b0, t1, t0);
                }
            }

            // 3. Generate end caps if requested
            if (capped)
            {
                // Bottom Cap at zMin (facing -Z)
                AddCapFace(mesh, sampledSections[0], zMin, isTopCap: false);

                // Top Cap at zMax (facing +Z)
                AddCapFace(mesh, sampledSections[sectionCount - 1], zMax, isTopCap: true);
            }

            // 4. Center along Z if requested
            if (centered)
            {
                double midZ = (zMin + zMax) / 2.0;
                mesh.Translate(new Vector3(0, 0, -midZ));
            }

            mesh.CleanAndMerge();
            return mesh;
        }

        private static void AddCapFace(Mesh mesh, List<Vector2> loop, double z, bool isTopCap)
        {
            if (loop == null || loop.Count < 3) return;

            var storage = new VertexStorage();
            storage.MoveTo(loop[0]);
            for (int i = 1; i < loop.Count; i++)
            {
                storage.LineTo(loop[i]);
            }
            storage.ClosePolygon();

            Mesh capMesh = storage.TriangulateFaces(zHeight: z);
            if (!isTopCap)
            {
                capMesh.ReverseFaces();
            }
            mesh.CopyFaces(capMesh);
        }

        internal static List<Vector2> SampleLoop(I2DPrimitive shape, int resolution, double twistDegrees)
            => SampleLoop(shape, resolution, twistDegrees, out _);

        internal static List<Vector2> SampleLoop(I2DPrimitive shape, int resolution, double twistDegrees, out Vector2 center)
        {
            center = Vector2.Zero;
            shape.ValidateClosed("loft");

            // 1. Extract vertices from shape
            var rawPoints = new List<Vector2>();
            IVertexSource vertexSource = shape.ToVertexSource();
            var flattened = new FlattenCurves(vertexSource);
            foreach (var v in flattened.Vertices())
            {
                if (v.IsStop) break;
                if (v.IsMoveTo || v.IsLineTo)
                {
                    if (rawPoints.Count == 0 || (rawPoints[rawPoints.Count - 1] - v.Position).LengthSquared > 1e-10)
                    {
                        rawPoints.Add(v.Position);
                    }
                }
            }

            if (rawPoints.Count >= 2 && (rawPoints[0] - rawPoints[rawPoints.Count - 1]).LengthSquared <= 1e-10)
            {
                rawPoints.RemoveAt(rawPoints.Count - 1);
            }

            if (rawPoints.Count < 3)
            {
                throw new InvalidOperationException($"Cannot loft {shape.GetType().Name}: shape does not have enough distinct vertices to form a closed 2D boundary.");
            }

            // 2. Ensure Counter-Clockwise (CCW) winding
            int m = rawPoints.Count;
            double signedArea = 0;
            for (int i = 0; i < m; i++)
            {
                int next = (i + 1) % m;
                signedArea += rawPoints[i].X * rawPoints[next].Y - rawPoints[next].X * rawPoints[i].Y;
            }

            if (signedArea < 0)
            {
                rawPoints.Reverse();
            }

            // 3. Compute polygon centroid
            double cx = 0, cy = 0;
            double a = 0;
            for (int i = 0; i < m; i++)
            {
                int next = (i + 1) % m;
                double cross = rawPoints[i].X * rawPoints[next].Y - rawPoints[next].X * rawPoints[i].Y;
                a += cross;
                cx += (rawPoints[i].X + rawPoints[next].X) * cross;
                cy += (rawPoints[i].Y + rawPoints[next].Y) * cross;
            }

            if (Math.Abs(a) > 1e-9)
            {
                cx /= (3.0 * a);
                cy /= (3.0 * a);
            }
            else
            {
                cx = 0; cy = 0;
                for (int i = 0; i < m; i++)
                {
                    cx += rawPoints[i].X;
                    cy += rawPoints[i].Y;
                }
                cx /= m;
                cy /= m;
            }
            center = new Vector2(cx, cy);

            // 4. Compute cumulative segment lengths
            double[] cumDist = new double[m + 1];
            cumDist[0] = 0;
            for (int i = 0; i < m; i++)
            {
                int next = (i + 1) % m;
                double len = (rawPoints[next] - rawPoints[i]).Length;
                cumDist[i + 1] = cumDist[i] + len;
            }
            double totalPerimeter = cumDist[m];
            if (totalPerimeter <= 1e-9)
            {
                throw new InvalidOperationException($"Cannot loft {shape.GetType().Name}: shape has zero perimeter.");
            }

            // 5. Seam alignment: find distance s along perimeter intersecting ray (cx + t, cy), t >= 0
            double sSeam = -1;
            double maxInterX = double.NegativeInfinity;

            for (int i = 0; i < m; i++)
            {
                int next = (i + 1) % m;
                Vector2 p1 = rawPoints[i];
                Vector2 p2 = rawPoints[next];

                double yMin = Math.Min(p1.Y, p2.Y);
                double yMax = Math.Max(p1.Y, p2.Y);

                if (cy >= yMin && cy <= yMax && Math.Abs(p2.Y - p1.Y) > 1e-9)
                {
                    double t = (cy - p1.Y) / (p2.Y - p1.Y);
                    if (t >= 0.0 && t <= 1.0)
                    {
                        double xInter = p1.X + t * (p2.X - p1.X);
                        if (xInter >= cx - 1e-6)
                        {
                            if (xInter > maxInterX)
                            {
                                maxInterX = xInter;
                                double segLen = cumDist[i + 1] - cumDist[i];
                                sSeam = cumDist[i] + t * segLen;
                            }
                        }
                    }
                }
            }

            // Fallback if ray didn't hit (e.g. centroid outside shape)
            if (sSeam < 0)
            {
                double minAngleDiff = double.MaxValue;
                for (int i = 0; i < m; i++)
                {
                    Vector2 p = rawPoints[i];
                    double angle = Math.Abs(Math.Atan2(p.Y - cy, p.X - cx));
                    if (angle < minAngleDiff)
                    {
                        minAngleDiff = angle;
                        sSeam = cumDist[i];
                    }
                }
            }

            if (sSeam < 0)
            {
                sSeam = 0;
            }

            // 6. Sample resolution points along the perimeter starting at sSeam
            var sampled = new List<Vector2>(resolution);

            for (int k = 0; k < resolution; k++)
            {
                double u = (double)k / resolution;
                double s = (sSeam + u * totalPerimeter) % totalPerimeter;
                if (s < 0) s += totalPerimeter;

                int seg = 0;
                for (int j = 0; j < m; j++)
                {
                    if (s <= cumDist[j + 1] || j == m - 1)
                    {
                        seg = j;
                        break;
                    }
                }

                int segNext = (seg + 1) % m;
                double segLen = cumDist[seg + 1] - cumDist[seg];
                double segT = segLen > 1e-9 ? (s - cumDist[seg]) / segLen : 0.0;
                segT = Math.Clamp(segT, 0.0, 1.0);

                Vector2 pt = (1.0 - segT) * rawPoints[seg] + segT * rawPoints[segNext];
                sampled.Add(pt);
            }

            // 7. Apply twist rotation around centroid if specified
            if (Math.Abs(twistDegrees) > 1e-6)
            {
                double twistRad = MathHelper.DegreesToRadians(twistDegrees);
                double cosT = Math.Cos(twistRad);
                double sinT = Math.Sin(twistRad);

                for (int i = 0; i < sampled.Count; i++)
                {
                    double dx = sampled[i].X - center.X;
                    double dy = sampled[i].Y - center.Y;
                    sampled[i] = new Vector2(
                        center.X + dx * cosT - dy * sinT,
                        center.Y + dx * sinT + dy * cosT);
                }
            }

            return sampled;
        }
    }
}
